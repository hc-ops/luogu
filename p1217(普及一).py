# s[:-1][::-1]（把去掉最后一位后的结果，全部反转）

# [::-1] 代表从后往前全部读取（反转）。所以 "12" 反转后变成了 "21"。

# s + s[:-1][::-1]（拼接在一起）

# "123" 加 "21"，就变成了 "12321"。

# int(...)（把拼出来的字符串转回数字）

