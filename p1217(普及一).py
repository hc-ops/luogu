import math
def is_prime(n):
    if n<2:
        return False
    for i in range(2,int(n**0.5)+1):
        if n%i==0:
            return False
    return True
a,b=input().split()
a=int(a)
b=int(b)
#单独处理1位数
for i in range(2,10):
    if i>=a and i<=b and is_prime(i):
        print(i)
#单独处理2位数，因为11是唯一的两位回文数
if 11>=a and 11<=b:
    print(11)
#处理三位数，再拼接
for i in range(10,100):
    s=str(i)
    pal=int(s+s[:-1][::-1])#先去掉最后一位，再反转剩下的
    if pal>=a and pal<=b and is_prime(pal):
        print(pal)
#处理五位数
